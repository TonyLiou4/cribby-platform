-- ----------------------------------------------------------------------------
-- refresh_tokens
-- Source: auth/entity/RefreshToken.java (extends BaseEntity)
-- Explicit @Index(name = "idx_refresh_tokens_token_hash", unique = true)
-- and @Index(name = "idx_refresh_tokens_user_id") from @Table(indexes = ...),
-- ON TOP OF the column-level unique=true on token_hash. Hibernate would
-- generate both a unique constraint AND the named unique index, so both
-- are reproduced here.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP NOT NULL,
    user_id     BIGINT NOT NULL,
    token_hash  VARCHAR(100) NOT NULL,
    expires_at  TIMESTAMP NOT NULL,
    revoked_at  TIMESTAMP,
    CONSTRAINT uk_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id)
        REFERENCES users (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_refresh_tokens_token_hash
    ON refresh_tokens (token_hash);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_id
    ON refresh_tokens (user_id);

-- ----------------------------------------------------------------------------
