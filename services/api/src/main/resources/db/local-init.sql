-- ============================================================================
-- Additional indexes (not declared on the entities, but not created
-- automatically by Postgres either — FK columns are NOT auto-indexed).
-- These match the query patterns actually used by the repositories
-- (ListingSpecifications, ConversationRepository, etc.) and are purely
-- additive: dropping this whole section changes no application behavior,
-- it only helps local query performance.
-- ============================================================================

-- Listing search/filter columns (ListingSpecifications: status, city,
-- universityName, roomType, genderPreference; ListingRepository: owner).
CREATE INDEX IF NOT EXISTS idx_listings_owner_id ON listings (owner_id);
CREATE INDEX IF NOT EXISTS idx_listings_status ON listings (status);
CREATE INDEX IF NOT EXISTS idx_listings_city ON listings (city);
CREATE INDEX IF NOT EXISTS idx_listings_university_name ON listings (university_name);

-- Listing images belong to a listing; fetched by listing_id.
CREATE INDEX IF NOT EXISTS idx_listing_images_listing_id ON listing_images (listing_id);

-- Favorites: compound unique already indexes (user_id, listing_id) leading
-- with user_id; add listing_id alone for "who favorited this listing" style
-- lookups.
CREATE INDEX IF NOT EXISTS idx_favorites_listing_id ON favorites (listing_id);

-- Conversations: looked up by listing and by either participant.
CREATE INDEX IF NOT EXISTS idx_conversations_listing_id ON conversations (listing_id);
CREATE INDEX IF NOT EXISTS idx_conversations_sender_id ON conversations (sender_id);
CREATE INDEX IF NOT EXISTS idx_conversations_receiver_id ON conversations (receiver_id);

-- Messages: fetched by conversation (message thread) and by sender.
CREATE INDEX IF NOT EXISTS idx_messages_conversation_id ON messages (conversation_id);
CREATE INDEX IF NOT EXISTS idx_messages_sender_id ON messages (sender_id);

-- Reports: moderation queues filter by reporter/reported user/listing.
CREATE INDEX IF NOT EXISTS idx_reports_reporter_id ON reports (reporter_id);
CREATE INDEX IF NOT EXISTS idx_reports_reported_user_id ON reports (reported_user_id);
CREATE INDEX IF NOT EXISTS idx_reports_reported_listing_id ON reports (reported_listing_id);
CREATE INDEX IF NOT EXISTS idx_reports_status ON reports (status);

-- Verification requests: admin review queue looks up by user and status.
CREATE INDEX IF NOT EXISTS idx_verification_requests_user_id ON verification_requests (user_id);
CREATE INDEX IF NOT EXISTS idx_verification_requests_status ON verification_requests (status);
