-- ============================================================================
-- Cribby / Roommate Marketplace — local dev schema bootstrap
--
-- Reconstructed from the JPA entities in
--   roommate-marketplace-api/src/main/java/com/santosh/roommate_marketplace_api/**
-- as of 2026-09-10, after a local PostgreSQL reinstall wiped the dev database.
--
-- This script is meant to be run ONCE against a freshly created, empty
-- `roommate_marketplace` database, before Spring Boot starts up with
-- spring.jpa.hibernate.ddl-auto=update. It recreates exactly the tables,
-- columns, keys, and indexes Hibernate would generate from the current
-- entity model, so `update` sees a schema that already matches and makes
-- no further changes.
--
-- Notes on fidelity to the entity model:
--  * All @Id fields use GenerationType.IDENTITY -> `bigint generated by
--    default as identity`, matching Hibernate 6 + PostgreSQLDialect.
--  * @Enumerated(EnumType.STRING) fields are stored as VARCHAR(length),
--    not native Postgres ENUM types — this is what Hibernate does by
--    default with EnumType.STRING, and it's what lets ddl-auto=update
--    keep working unmodified if enum values are added later.
--  * Java field initializers (e.g. `= UserType.OTHER`, `= false`) are
--    application-layer defaults only. Hibernate's schema generation does
--    NOT translate them into SQL DEFAULT clauses (no @ColumnDefault is
--    used anywhere in this codebase), so this script does not add DB-level
--    defaults either — this keeps the script's output identical to what
--    ddl-auto=update would create from scratch. In practice this means
--    the application always sets these columns explicitly on insert, so
--    it's only relevant if you plan to insert rows with raw SQL yourself.
--  * java.time.LocalDateTime -> `timestamp` (no time zone).
--    java.time.Instant (used only in UserProfile) -> `timestamptz`
--    (Hibernate 6 maps Instant to TIMESTAMP WITH TIME ZONE by default).
--    java.time.LocalDate -> `date`.
--  * Foreign key / unique constraint names below are our own descriptive
--    names, except `uk_favorites_user_listing`, `idx_refresh_tokens_*`,
--    and `idx_email_verification_*`, which are pulled verbatim from
--    explicit @UniqueConstraint / @Index annotations in the entities.
--    Hibernate's ddl-auto=update does not manage or validate constraint
--    names, so our own naming elsewhere causes no conflicts.
--  * No @ManyToMany relationships and no join tables exist in this model,
--    so none are created here.
--  * Tables are created in FK-dependency order so this can be run
--    top-to-bottom in one pass.
--
-- Usage:
--   psql -d roommate_marketplace -f src/main/resources/db/local-init.sql
--
-- Safe to re-run: every statement is IF NOT EXISTS / guarded, so running
-- it again against a database that already has these tables is a no-op.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- users
-- Source: user/entity/User.java (extends BaseEntity)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP NOT NULL,
    first_name          VARCHAR(100),
    last_name           VARCHAR(100),
    email               VARCHAR(320) NOT NULL,
    password            VARCHAR(255) NOT NULL,
    phone_number        VARCHAR(30),
    university_name     VARCHAR(160),
    user_type           VARCHAR(30) NOT NULL,
    role                VARCHAR(30) NOT NULL,
    email_verified      BOOLEAN NOT NULL,
    student_verified    BOOLEAN NOT NULL,
    alumni_verified     BOOLEAN NOT NULL,
    phone_verified      BOOLEAN NOT NULL,
    id_verified         BOOLEAN NOT NULL,
    profile_photo_url   VARCHAR(500),
    bio                 VARCHAR(1000),
    gender              VARCHAR(40),
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- ----------------------------------------------------------------------------
-- user_profiles
-- Source: user/entity/UserProfile.java (own @Id, uses Instant timestamps)
-- 1:1 with users, FK column carries the uniqueness (User.profile is the
-- inverse/mappedBy side).
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_profiles (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT NOT NULL,
    display_name            VARCHAR(120) NOT NULL,
    profile_photo_url       VARCHAR(500),
    university              VARCHAR(160),
    bio                     VARCHAR(1000),
    city                    VARCHAR(120),
    roommate_preferences    VARCHAR(1000),
    created_at              TIMESTAMPTZ NOT NULL,
    updated_at              TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_user_profiles_user_id UNIQUE (user_id),
    CONSTRAINT fk_user_profiles_user FOREIGN KEY (user_id)
        REFERENCES users (id)
);

-- ----------------------------------------------------------------------------
-- listings
-- Source: listing/entity/Listing.java (extends BaseEntity)
